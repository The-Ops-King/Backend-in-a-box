import fs from "node:fs";
import path from "node:path";
import { templates } from "@/templates";
import { Node, extractManifest, parseDefinition, type Definition } from "./definition";
import { EVENT_LABELS } from "./describe";
import { EVENT_SOURCES, STEP_DOCS } from "./step-docs";

/**
 * D144 (Tyler: "one inventory of templates, one of triggers and one of steps"): the three, made from the code so they cannot go
 * stale (scripts/inventory.ts writes them to engine/inventory/; a test fails when they are out of date).
 */
const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");
const SENDS = new Set(["send_sms", "send_email", "send_document"]);
type Trig = { event: string; match?: unknown; schedule?: Record<string, unknown> };
const triggersOf = (def: Definition): Trig[] => def.nodes.flatMap((n) => (n.type === "trigger" ? [{ event: n.event, match: n.match, schedule: n.schedule as Record<string, unknown> | undefined }] : []));
const when = (t: Trig) => (t.schedule ? `schedule ${JSON.stringify(t.schedule)}` : `${t.event}${t.match ? ` when ${JSON.stringify(t.match)}` : ""}`);

/** A company's own copies: every installs/<company>/*.json that holds a definition. */
export function companyCopies(root: string): { company: string; file: string; name: string; note: string; def: Definition }[] {
  const dir = path.join(root, "installs");
  return fs.readdirSync(dir, { withFileTypes: true }).filter((d) => d.isDirectory()).flatMap((d) =>
    fs.readdirSync(path.join(dir, d.name)).filter((f) => f.endsWith(".json")).flatMap((f) => {
      const j = JSON.parse(fs.readFileSync(path.join(dir, d.name, f), "utf8")) as { name?: string; workflow?: string; note?: string; definition?: unknown };
      if (!j.definition) return [];
      return [{ company: d.name, file: f, name: j.name ?? j.workflow ?? f.replace(/\.json$/, ""), note: j.note ?? "", def: parseDefinition(j.definition) }];
    })).sort((a, b) => a.company.localeCompare(b.company) || a.file.localeCompare(b.file));
}

export function templatesInventory(root: string): string {
  const lines = ["# Templates", "", "Generated by `scripts/inventory.ts` from `src/templates` and `installs/*/` (D144). Do not edit by hand.", "",
    "| template | stage | starts on | steps | settings it needs (required in bold) | reaches the contact |", "|---|---|---|---|---|---|"];
  for (const t of [...templates].sort((a, b) => a.slug.localeCompare(b.slug))) {
    const def = parseDefinition(t.definition), m = extractManifest(def);
    const counts = Object.entries(def.nodes.reduce<Record<string, number>>((o, n) => ({ ...o, [n.type]: (o[n.type] ?? 0) + 1 }), {})).filter(([k]) => k !== "trigger").sort().map(([k, v]) => `${k}×${v}`).join(", ");
    const needs = m.bindings.map((b) => (b.required ? `**${b.key}**` : b.key)).join(", ");
    const sends = [...new Set(def.nodes.filter((n) => SENDS.has(n.type)).map((n) => n.type.replace("send_", "")))].join(", ") || "no";
    lines.push(`| \`${t.slug}\` ${cell(t.name)} | ${t.stage} | ${cell(triggersOf(def).map(when).join("; "))} | ${counts} | ${needs} | ${sends} |`);
  }
  lines.push("", "## Company copies", "", "| company | workflow | starts on | what it is |", "|---|---|---|---|");
  for (const x of companyCopies(root)) lines.push(`| ${x.company} | ${cell(x.name)} | ${cell(triggersOf(x.def).map(when).join("; "))} | ${cell(x.note.split(/(?<=\.)\s/)[0] ?? "")} |`);
  return lines.join("\n") + "\n";
}

export function triggersInventory(root: string): string {
  const starts = new Map<string, string[]>();
  const add = (event: string, who: string) => starts.set(event, [...(starts.get(event) ?? []), who]);
  for (const t of templates) for (const tr of triggersOf(parseDefinition(t.definition))) add(tr.event, `\`${t.slug}\``);
  for (const x of companyCopies(root)) for (const tr of triggersOf(x.def)) add(tr.event, `${x.company}/${x.file.replace(/\.json$/, "")}`);
  const events = [...new Set([...Object.keys(EVENT_LABELS), ...Object.keys(EVENT_SOURCES), ...starts.keys()])].sort();
  const lines = ["# Triggers", "", "Generated by `scripts/inventory.ts` from the event labels, `src/engine/step-docs.ts` and the workflows (D144). Do not edit by hand.", "",
    "| event | what it means | written by | workflows that start on it |", "|---|---|---|---|"];
  for (const e of events) lines.push(`| \`${e}\` | ${cell(EVENT_LABELS[e] ?? "")} | ${cell(EVENT_SOURCES[e] ?? "nothing writes it")} | ${[...new Set(starts.get(e) ?? [])].join(", ") || "none"} |`);
  return lines.join("\n") + "\n";
}

export function stepsInventory(): string {
  const base = new Set(["id", "type", "title", "only_if", "blocking"]);
  const lines = ["# Steps", "", "Generated by `scripts/inventory.ts` from `src/engine/definition.ts` and `src/engine/step-docs.ts` (D144). Do not edit by hand.",
    "Every step also takes `title`, `only_if` (skipped when false) and `blocking`.", "",
    "| step | parameters | what it does | company settings it reads |", "|---|---|---|---|"];
  for (const o of [...Node.options].sort((a, b) => String(a.shape.type.value).localeCompare(String(b.shape.type.value)))) {
    const type = o.shape.type.value as keyof typeof STEP_DOCS, doc = STEP_DOCS[type];
    const params = Object.keys(o.shape).filter((k) => !base.has(k)).map((k) => `\`${k}\``).join(", ");
    lines.push(`| \`${type}\` | ${params || "none"} | ${cell(doc.does)} | ${cell((doc.reads ?? []).join(", ")) || "none"} |`);
  }
  return lines.join("\n") + "\n";
}

export const INVENTORY_FILES = (root: string) => ({ "templates.md": templatesInventory(root), "triggers.md": triggersInventory(root), "steps.md": stepsInventory() });
